"""Bounded search over manipulation effects, grounded in an observed scene.

The search certifies symbolic preconditions, not physical executability. All
operators compile to the existing contact-verified controllers. No code or motor
trajectory is generated by a model, and no predicted state is written to Genesis.
"""
from __future__ import annotations

import heapq
import itertools
import math

from backend.app.models.schemas import AgentPlan, PlanStep
from backend.app.planning.task_program import (
    GroundingError, TABLE_TARGETS, TaskAction, TaskGoal, TaskProgram,
    compile_program, observed_holds,
)


def action_key(action: TaskAction) -> tuple:
    return tuple(getattr(action, name) for name in
                 ('op', 'object', 'arm', 'receiver', 'target', 'relation', 'distance_cm'))


def _relative_position(obj, reference, relation, distance_cm=None, arm='left'):
    a, b = obj.get('bounds'), reference.get('bounds')
    if a is None or b is None:
        return None
    position = list(reference['position'])
    bottom = obj['position'][2] - a[0][2]
    if relation == 'on':
        position[2] = b[1][2] + bottom
    else:
        directions = {'left_of': (0, 1), 'right_of': (0, -1), 'front_of': (1, 0),
                      'behind': (-1, 0), 'near': (0, 1 if arm == 'left' else -1)}
        dx, dy = directions[relation]
        half_x = (a[1][0]-a[0][0]+b[1][0]-b[0][0])/2
        half_y = (a[1][1]-a[0][1]+b[1][1]-b[0][1])/2
        gap = .03 if distance_cm is None else distance_cm/100
        position[0] += dx*(half_x+gap)
        position[1] += dy*(half_y+gap)
        position[2] = b[0][2]+bottom+.003
    return position


def goal_holds(goal: TaskGoal, state: dict) -> bool:
    """Conservative snapshot test; final success still uses the physics verifier."""
    objects = {obj['id']: obj for obj in state['objects']}
    obj = objects[goal.object]
    holders = [arm for arm, name in observed_holds(state).items() if name == goal.object]
    if goal.type == 'holding':
        bounds = obj.get('bounds')
        return holders == [goal.arm] and bounds is not None and bounds[0][2] > state.get('workspace', {}).get('table_height_m', 1.008)+.008
    if holders or obj.get('linear_speed_m_s', 0.) >= .02:
        return False
    if goal.type == 'placement':
        targets = {**TABLE_TARGETS, **{x['id']: x['position'] for x in state['targets']}}
        target = targets[goal.target]
        return math.dist(obj['position'][:2], target[:2]) <= .04 and abs(obj['position'][2]-target[2]) <= .05
    reference = objects[goal.target]
    if goal.target in observed_holds(state).values() or reference.get('linear_speed_m_s', 0.) >= .02:
        return False
    if goal.relation == 'on':
        a, b = obj.get('bounds'), reference.get('bounds')
        if a is None or b is None or goal.target not in obj.get('touching', []):
            return False
        overlap = math.prod(max(0., min(a[1][i],b[1][i])-max(a[0][i],b[0][i])) for i in (0,1))
        area = min(math.prod(a[1][i]-a[0][i] for i in (0,1)), math.prod(b[1][i]-b[0][i] for i in (0,1)))
        rotation = obj.get('rotation')
        return (area > 0 and overlap/area >= .65 and abs(a[0][2]-b[1][2]) < .004
                and math.dist(obj['position'][:2], reference['position'][:2]) <= .012
                and rotation is not None and max(map(abs, rotation[2])) > math.cos(.20))
    for arm in ('left', 'right') if goal.relation == 'near' else ('left',):
        desired = _relative_position(obj, reference, goal.relation, goal.distance_cm, arm)
        if desired is not None and math.dist(obj['position'][:2], desired[:2]) <= .015 and abs(obj['position'][2]-desired[2]) < .006:
            return True
    return False


class GoalDomain:
    """Finite object locations + hand occupancy; explicit frame constraints."""
    def __init__(self, program: TaskProgram, state: dict, initial_state: dict | None = None):
        self.program, self.state = program, state
        self.objects = {obj['id']: obj for obj in state['objects']}
        self.names = tuple(sorted(self.objects))
        self.index = {name: i for i, name in enumerate(self.names)}
        self.goals = {}
        for goal in program.goals:
            if goal.object not in self.objects or not goal.object.endswith('_cube'):
                raise GroundingError('Goal search currently requires known rigid cubes')
            if goal.object in self.goals and goal != self.goals[goal.object]:
                raise GroundingError(f'Conflicting final goals for {goal.object}')
            self.goals[goal.object] = goal
        self.targets = {**TABLE_TARGETS, **{x['id']: x['position'] for x in state['targets']}}
        self.arms = state.get('robot', {}).get('available_arms', ['left', 'right'])
        grippers = state.get('robot', {}).get('grippers')
        if grippers is not None:
            self.arms = [arm for arm in self.arms if arm in grippers]
        self.allowed = state.get('capabilities', {}).get('skills')
        for goal in self.goals.values():
            if goal.type == 'holding' and goal.arm not in self.arms:
                raise GroundingError(f'ROBOT_CAPABILITY: no detected gripper for {goal.arm}')
            if goal.type == 'placement' and goal.target not in self.targets:
                raise GroundingError(f'Unknown placement target: {goal.target}')
            if goal.type == 'relative_placement' and (goal.target not in self.objects or not goal.target.endswith('_cube') or goal.target == goal.object):
                raise GroundingError('Relative goal needs a different known reference cube')
        requested = [g.arm for g in self.goals.values() if g.type == 'holding']
        if len(requested) != len(set(requested)):
            raise GroundingError('Two final objects cannot occupy one hand')
        if any(name not in self.objects for name in program.keep_in_place):
            raise GroundingError('Unknown keep_in_place object')
        self.movable = set(self.goals)-set(program.keep_in_place)
        initial = {x['id']: x for x in (initial_state or state)['objects']}
        self.protected = {name: initial[name]['position'] for name in self.names if name not in self.movable}
        self.assert_preserved(state)

    def assert_preserved(self, state):
        current = {x['id']: x['position'] for x in state['objects']}
        for name, position in self.protected.items():
            if name not in current or math.dist(current[name], position) >= .006:
                raise GroundingError(f'PRESERVATION_VIOLATION: {name} moved from its protected position')

    def enabled(self, *skills):
        return self.allowed is None or all(skill in self.allowed for skill in skills)

    def desired(self, goal):
        if goal.type == 'holding':
            return ('held', goal.arm)
        if goal.type == 'placement':
            return ('zone', goal.target)
        return ('relative', goal.target, goal.relation, goal.distance_cm)

    def project(self, state):
        holds = observed_holds(state)
        locations = []
        for name in self.names:
            owners = [arm for arm, obj in holds.items() if obj == name]
            if len(owners) > 1:
                raise GroundingError('Finish the partial handover before goal search')
            if owners:
                obj = next(x for x in state['objects'] if x['id'] == name)
                bounds = obj.get('bounds')
                elevated = bounds is not None and bounds[0][2] > state.get('workspace', {}).get('table_height_m', 1.008)+.008
                locations.append(('held' if elevated else 'pinched', owners[0]))
            elif name in self.goals and goal_holds(self.goals[name], state):
                locations.append(self.desired(self.goals[name]))
            else:
                parent = next((r['object'] for r in state.get('support_relations', []) if r['subject'] == name and r['relation'] == 'on'), None)
                if parent:
                    locations.append(('supported', parent))
                else:
                    obj = next(x for x in state['objects'] if x['id'] == name)
                    zones = [zone for zone, position in self.targets.items()
                             if math.dist(obj['position'][:2], position[:2]) <= .04 and abs(obj['position'][2]-position[2]) <= .05]
                    locations.append(('zone', min(zones, key=lambda z: math.dist(obj['position'], self.targets[z]))) if zones else ('initial', name))
        return (*locations, ('ready', *sorted(state.get('robot', {}).get('handover_ready', []))))

    def satisfied(self, node):
        return all(node[self.index[name]] == self.desired(goal) for name, goal in self.goals.items())

    def _clear(self, node, name):
        return not any(loc[0] == 'supported' and loc[1] == name or
                       loc[0] == 'relative' and loc[1:3] == (name, 'on') for loc in node)

    def _position(self, node, name, seen=()):
        loc = node[self.index[name]]
        if loc[0] == 'zone':
            return self.targets[loc[1]]
        if loc[0] in {'supported', 'relative'} and loc[1] not in seen:
            original = self.objects[loc[1]]['position']
            moved = self._position(node, loc[1], (*seen, name))
            if loc[0] == 'relative':
                desired = _relative_position(self.objects[name], self.objects[loc[1]], loc[2], loc[3])
                if desired is not None:
                    return [a+b-c for a,b,c in zip(desired, moved, original)]
            return [a+b-c for a,b,c in zip(self.objects[name]['position'], moved, original)]
        return self.objects[name]['position']

    def _buffer_clear(self, node, name, point):
        def half_width(obj, axis):
            bounds = self.objects[obj].get('bounds')
            return (bounds[1][axis]-bounds[0][axis])/2 if bounds else .025
        for other in self.names:
            if other == name or node[self.index[other]][0] == 'held':
                continue
            position = self._position(node, other)
            if all(abs(point[i]-position[i]) < half_width(name,i)+half_width(other,i)+.008 for i in (0,1)):
                return False
        return True

    def transitions(self, node):
        occupied = {loc[1]: name for name, loc in zip(self.names, node) if loc[0] in {'held', 'pinched'}}
        ready = set(node[-1][1:])
        def changed(name, loc, touched=(), prepared=None):
            next_ready = ready-set(touched)
            if prepared:
                next_ready.add(prepared)
            positions = tuple(loc if other == name else node[i] for i, other in enumerate(self.names))
            return (*positions, ('ready', *sorted(next_ready)))
        if self.enabled('return_home', 'park_empty_arm'):
            for arm in self.arms:
                if arm not in occupied and arm not in ready:
                    yield TaskAction(op='home', arm=arm), changed(None, None, prepared=arm), .4
        for name in sorted(self.movable):
            loc = node[self.index[name]]
            if loc[0] == 'pinched':
                yield TaskAction(op='pick', object=name, arm=loc[1]), changed(name, ('held', loc[1]), touched=[loc[1]]), .5
                continue
            if loc[0] != 'held':
                if not self.objects[name].get('graspable', True) or not self._clear(node, name) or not self.enabled('approach_object', 'grasp_object', 'lift_object'):
                    continue
                position = self._position(node, name)
                preferred = self.objects[name].get('admitted_grasp_arm') if loc[0] == 'initial' else None
                preferred = preferred or ('left' if position[1] >= 0 else 'right')
                for arm in self.arms:
                    if arm not in occupied:
                        cost = 1. + (0. if arm == preferred else 4.)
                        yield TaskAction(op='pick', object=name, arm=arm), changed(name, ('held', arm), touched=[arm]), cost
                continue
            arm = loc[1]
            if self.enabled('handover_object'):
                for receiver in self.arms:
                    if receiver != arm and receiver not in occupied and receiver in ready:
                        yield TaskAction(op='handover', object=name, arm=arm, receiver=receiver), changed(name, ('held', receiver), touched=[arm, receiver]), 2.5
            if not self.enabled('move_to_target', 'release_object', 'retreat'):
                continue
            # Table regions serve as buffers, including when both hands are full.
            for target in sorted(self.targets):
                point = self.targets[target]
                if not self._buffer_clear(node, name, point):
                    continue
                action = TaskAction(op='place', object=name, arm=arm, target=target)
                preferred = 'left' if point[1] >= 0 else 'right'
                cross = 3. if abs(point[1]) > .12 and preferred != arm else 0.
                yield action, changed(name, ('zone', target), touched=[arm]), 2.5+cross+math.dist(self._position(node, name)[:2], point[:2])
            goal = self.goals[name]
            if (goal.type == 'relative_placement' and self.enabled('move_to_object')
                    and node[self.index[goal.target]][0] != 'held'
                    and (goal.relation != 'on' or self._clear(node, goal.target))):
                action = TaskAction(op='place', object=name, arm=arm, target=goal.target,
                                    relation=goal.relation, distance_cm=goal.distance_cm)
                reference = self.objects[goal.target]
                preferred = reference.get('admitted_grasp_arm') or ('left' if self._position(node, goal.target)[1] >= 0 else 'right')
                yield action, changed(name, self.desired(goal), touched=[arm]), 1.5+(3. if preferred != arm else 0.)


def compile_goal_program(program: TaskProgram, state: dict, *, initial_state=None,
                         blocked=frozenset(), max_states=4000) -> AgentPlan:
    domain = GoalDomain(program, state, initial_state)
    start = domain.project(state)
    # Parking an empty arm does not erase a failed object/hand transition.
    # Otherwise search could evade feedback by adding a home action and repeat
    # exactly the rejected pickup in the same object/occupancy state.
    blocked = {(node[:-1] if node and node[-1][0] == 'ready' else node, key) for node, key in blocked}
    counter = itertools.count()
    queue = [(0., next(counter), start, ())]
    best = {start: 0.}
    expanded, selected = 0, None
    while queue and expanded < max_states:
        cost, _, node, actions = heapq.heappop(queue)
        if cost > best[node]:
            continue
        expanded += 1
        if domain.satisfied(node):
            selected = actions
            break
        if len(actions) >= 24:
            continue
        for action, after, extra in domain.transitions(node):
            if (node[:-1], action_key(action)) in blocked:
                continue
            new_cost = cost+extra
            if new_cost < best.get(after, math.inf):
                best[after] = new_cost
                heapq.heappush(queue, (new_cost, next(counter), after, (*actions, action)))
    if selected is None:
        category = 'GOAL_SEARCH_BUDGET' if queue else 'GOAL_UNREACHABLE'
        raise GroundingError(f'{category}: no contract-valid plan after {expanded} states; hand occupancy, supports, protected objects and capabilities were retained')
    if selected:
        plan = compile_program(TaskProgram(actions=list(selected)), state)
        # Goal-search preparation must clear table objects before changing the
        # empty wrist posture. Legacy home remains unchanged for ordered tasks.
        for step in plan.steps:
            if step.skill == 'return_home':
                step.skill = 'park_empty_arm'
    else:
        arm = next(iter(state.get('robot', {}).get('available_arms', ['left', 'right'])))
        plan = AgentPlan(goal={}, arm=arm, steps=[PlanStep(skill='observe_scene', arm=arm)], program={'actions': []})
    checks = []
    for goal in domain.goals.values():
        check = goal.model_dump(exclude_none=True)
        if goal.type == 'relative_placement':
            placed = next((a for a in reversed(selected) if a.op == 'place' and a.object == goal.object), None)
            check['arm'] = placed.arm if placed else ('left' if domain.objects[goal.object]['position'][1] >= domain.objects[goal.target]['position'][1] else 'right')
        checks.append(check)
    checks.extend({'type': 'preserved', 'object': name, 'position': position} for name, position in domain.protected.items())
    plan.goal = {'type': 'goal_program', 'checks': checks}
    plan.goal_program = program.model_dump()
    plan.planning_evidence = {'method': 'bounded_uniform_cost_search', 'expanded_states': expanded,
        'actions': len(selected), 'protected_objects': sorted(domain.protected),
        'symbolic_preconditions_verified': True, 'physical_execution_verified': False}
    plan.assumptions.append('最終状態を目標に、一時置きや受け渡しを含む手順を探索します。実行後に状態を確認して更新します。')
    return plan
